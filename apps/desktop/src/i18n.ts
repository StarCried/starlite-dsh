export type UiLocale = "zh-CN" | "en";
let locale: UiLocale = "zh-CN";

/** Translate application-owned strings only. Never pass session/model content here. */
export function setUiLocale(value: unknown): UiLocale {
  locale = typeof value === "string" && value.trim() && !/^zh(?:-|$)/iu.test(value) ? "en" : "zh-CN";
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  return locale;
}
export function uiLocale(): UiLocale { return locale; }
export function t(source: string): string { return locale === "en" ? EN[source] ?? source : source; }
export function format(source: string, values: Record<string, string | number>): string {
  return t(source).replace(/\{(\w+)\}/gu, (match, key: string) => String(values[key] ?? match));
}

/** Fixed Host notices have a separate wire kind from model reasoning/response. */
export function hostNotice(source: string): string {
  const tool = /^正在使用 (.+)…$/u.exec(source);
  if (tool) return format("正在使用 {tool}…", {tool:tool[1]!});
  const approval = /^等待批准：(.+)$/u.exec(source);
  if (approval) return format("等待批准：{tool}", {tool:approval[1]!});
  return t(source);
}

/** Called once on the static application template, before any model/session data is rendered. */
export function translateTemplate(root: HTMLElement): void {
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walk.nextNode()) {
    const node = walk.currentNode;
    const source = node.textContent ?? "";
    const trimmed = source.trim();
    if (trimmed && Object.hasOwn(EN, trimmed)) node.textContent = source.replace(trimmed, t(trimmed));
  }
  for (const element of root.querySelectorAll<HTMLElement>("[aria-label], [title], [placeholder]")) {
    for (const attribute of ["aria-label", "title", "placeholder"]) {
      const value = element.getAttribute(attribute);
      if (value !== null) element.setAttribute(attribute, t(value));
    }
  }
}

